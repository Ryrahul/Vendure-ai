import { BadRequestException, Body, Controller, Inject, Post, Res, Logger } from '@nestjs/common';
import { Response } from 'express';
import { Allow, Ctx, CustomerService, Permission, RequestContext } from '@vendure/core';
import {
    AiChatService,
    AiChatProduct,
    AiChatCollection,
    AddToCartAction,
    AiChatOrder,
    AiChatOrderLine,
    AiActiveOrder,
    AiCartLine,
    SetShippingAddressAction,
    SetBillingAddressAction,
    SetShippingMethodAction,
} from '../services/ai-chat.service';
import { ConversationCacheService } from '../services/conversation-cache.service';
import { ChatLimitsService } from '../services/chat-limits.service';
import { AI_ASSISTANT_OPTIONS, sanitizeHistory, type AiAssistantPluginOptions } from '../constants';

/** Client-generated conversation ids: opaque, URL-safe, long enough to be unguessable. */
const CONVERSATION_ID_PATTERN = /^[A-Za-z0-9_-]{16,100}$/;

export type {
    AiChatProduct,
    AiChatCollection,
    AddToCartAction,
    AiChatOrder,
    AiChatOrderLine,
    AiActiveOrder,
    AiCartLine,
    SetShippingAddressAction,
    SetBillingAddressAction,
    SetShippingMethodAction,
} from '../services/ai-chat.service';

export interface AiChatRequest {
    /** Direct message (simple format) */
    message?: string;
    /** Conversation history from the frontend for multi-turn context (simple format) */
    history?: Array<{ role: 'user' | 'assistant'; content: string }>;
    /** AI SDK UIMessage array (sent by DefaultChatTransport / useChat()) */
    messages?: Array<{
        role: string;
        content?: string;
        parts?: Array<{ type: string; text?: string; [key: string]: unknown }>;
        [key: string]: unknown;
    }>;
    /**
     * Conversation ID for server-side history caching.
     * When provided, the server fetches conversation history from its cache
     * instead of requiring the full history in every request.
     * Generated by the frontend (UUID) when the chat widget mounts.
     */
    conversationId?: string;
}

export interface AiChatResponse {
    message: string;
    products: AiChatProduct[];
    collections: AiChatCollection[];
    addToCartAction?: AddToCartAction;
    orders?: AiChatOrder[];
    activeOrder?: AiActiveOrder;
    setShippingAddressAction?: SetShippingAddressAction;
    setBillingAddressAction?: SetBillingAddressAction;
    setShippingMethodAction?: SetShippingMethodAction;
}

/**
 * REST endpoints for the AI shopping assistant.
 * - POST /ai-assistant/chat — non-streaming JSON response (backward compatible)
 * - POST /ai-assistant/stream — streaming response using Vercel AI SDK data stream protocol
 */
@Controller('ai-assistant')
export class AiAssistantController {
    private readonly logger = new Logger(AiAssistantController.name);

    private readonly cacheEnabled: boolean;

    constructor(
        @Inject(AI_ASSISTANT_OPTIONS) private options: AiAssistantPluginOptions,
        private customerService: CustomerService,
        private aiChatService: AiChatService,
        private chatLimits: ChatLimitsService,
        private conversationCacheService: ConversationCacheService,
    ) {
        this.cacheEnabled = options.enableConversationCache !== false;
        this.logger.log(`Conversation cache: ${this.cacheEnabled ? 'enabled' : 'disabled'}`);
    }

    /**
     * Helper: extract user message and conversation history from the request body.
     * Supports two formats:
     * 1. Simple: { message: "hello", history: [{role, content}] }
     * 2. AI SDK: { messages: [UIMessage, ...] } (sent by DefaultChatTransport / useChat())
     */
    private extractMessageAndHistory(body: AiChatRequest): {
        message: string;
        history: Array<{ role: 'user' | 'assistant'; content: string }>;
    } {
        // AI SDK format: messages array with parts
        if (body.messages && Array.isArray(body.messages) && body.messages.length > 0) {
            const msgs = body.messages;
            const lastUserMsg = [...msgs].reverse().find(m => m.role === 'user');
            const message = lastUserMsg ? this.getTextFromUIMessage(lastUserMsg) : '';

            const lastUserIndex = msgs.lastIndexOf(lastUserMsg!);
            const historyMsgs = lastUserIndex > 0 ? msgs.slice(0, lastUserIndex) : [];
            const history = historyMsgs
                .filter(m => m.role === 'user' || m.role === 'assistant')
                .map(m => ({
                    role: m.role as 'user' | 'assistant',
                    content: m.role === 'assistant'
                        ? this.getAssistantTextWithToolContext(m)
                        : this.getTextFromUIMessage(m),
                }))
                .filter(m => m.content.length > 0);

            return { message: message.trim(), history };
        }

        // Simple format: { message, history }
        return {
            message: (typeof body.message === 'string' ? body.message : '').trim(),
            history: sanitizeHistory(body.history, Number.MAX_SAFE_INTEGER),
        };
    }

    /** Extract plain text from a UIMessage (handles both parts and content) */
    private getTextFromUIMessage(msg: Record<string, unknown>): string {
        if (Array.isArray(msg.parts)) {
            return (msg.parts as Array<Record<string, unknown>>)
                .filter(p => p.type === 'text' && typeof p.text === 'string')
                .map(p => p.text as string)
                .join('');
        }
        if (typeof msg.content === 'string') {
            return msg.content;
        }
        return '';
    }

    /** Extract assistant text + tool result summaries for conversation context */
    private getAssistantTextWithToolContext(msg: Record<string, unknown>): string {
        if (!Array.isArray(msg.parts)) {
            return typeof msg.content === 'string' ? msg.content : '';
        }
        const parts: string[] = [];
        for (const p of msg.parts as Array<Record<string, unknown>>) {
            if (p.type === 'text' && typeof p.text === 'string') {
                parts.push(p.text);
            }
            if (typeof p.type === 'string' && p.state === 'output-available' && p.output) {
                const output = p.output as Record<string, unknown>;
                if (typeof output.summary === 'string') {
                    parts.push(`[Tool result: ${output.summary}]`);
                }
            }
        }
        return parts.join('\n');
    }

    /**
     * Resolve conversation history: prefer server-side cache when conversationId
     * is present, otherwise fall back to the history sent in the request body.
     */
    private async resolveHistory(body: AiChatRequest, ownerKey: string): Promise<{
        message: string;
        history: Array<{ role: 'user' | 'assistant'; content: string }>;
        conversationId?: string;
    }> {
        const { message, history: rawBodyHistory } = this.extractMessageAndHistory(body);
        const maxLength = this.options.maxMessageLength ?? 2000;
        if (message.length > maxLength) {
            throw new BadRequestException(`Message too long (max ${maxLength} characters)`);
        }
        const maxHistory = this.options.maxHistoryMessages ?? 20;
        const bodyHistory = sanitizeHistory(rawBodyHistory, maxHistory);
        const conversationId =
            typeof body.conversationId === 'string' && CONVERSATION_ID_PATTERN.test(body.conversationId)
                ? body.conversationId
                : undefined;

        if (this.cacheEnabled && conversationId) {
            // Fetch history from server-side cache, scoped to this customer/session
            const cached = await this.conversationCacheService.getHistory(ownerKey, conversationId);
            const history = sanitizeHistory(cached?.messages, maxHistory);
            this.logger.debug(
                `[CACHE] Conversation ${conversationId}: ${history.length} cached messages (skipped ${bodyHistory.length} from request body)`,
            );
            return { message, history, conversationId };
        }

        // Cache disabled or no conversationId — fall back to history from request body
        return { message, history: bodyHistory };
    }

    /**
     * The customer (if logged in) and an owner key that scopes cached conversations to
     * this customer, or to this session for guests.
     */
    private async resolveCustomer(ctx: RequestContext) {
        let customerId: string | number | undefined;
        if (ctx.activeUserId) {
            const customer = await this.customerService.findOneByUserId(ctx, ctx.activeUserId);
            customerId = customer?.id;
        }
        const ip = ctx.req?.ip;
        const ownerKey = customerId != null ? `customer:${customerId}` : ctx.session?.id ? `session:${ctx.session.id}` : 'anonymous';
        // Usage limits apply per customer, else per session, else per IP address.
        const limitKey = ownerKey !== 'anonymous' ? ownerKey : `ip:${ip ?? 'unknown'}`;
        return { customerId, ownerKey, limitKey, ip };
    }

    /**
     * Non-streaming endpoint (backward compatible).
     * Returns the full JSON response after all tool calls complete.
     */
    @Post('chat')
    @Allow(Permission.Public)
    async chat(@Ctx() ctx: RequestContext, @Body() body: AiChatRequest): Promise<AiChatResponse> {
        const { customerId, ownerKey, limitKey, ip } = await this.resolveCustomer(ctx);
        const { message: query, history, conversationId } = await this.resolveHistory(body, ownerKey);

        if (!query) {
            return {
                message: 'Hi! I\'m your shopping assistant. How can I help you today? You can ask me about products, collections, your orders, or anything about our store.',
                products: [],
                collections: [],
            };
        }

        await this.chatLimits.checkBeforeChat('shop', limitKey, ip);
        const result = await this.aiChatService.chat(ctx, query, history, customerId);
        await this.chatLimits.recordUsage('shop', limitKey, result.usage?.totalTokens);

        // Cache the new turn if conversationId is present
        if (conversationId) {
            await this.conversationCacheService.appendMessages(
                ownerKey,
                conversationId,
                query,
                result.message,
                customerId,
            );
        }

        return {
            message: result.message,
            products: result.products,
            collections: result.collections,
            addToCartAction: result.addToCartAction,
            orders: result.orders,
            activeOrder: result.activeOrder,
            setShippingAddressAction: result.setShippingAddressAction,
            setBillingAddressAction: result.setBillingAddressAction,
            setShippingMethodAction: result.setShippingMethodAction,
        };
    }

    /**
     * Streaming endpoint.
     * Returns a Vercel AI SDK–compatible data stream.
     * The frontend can consume this with useChat() from @ai-sdk/react.
     *
     * Structured data (products, collections, cart, orders, actions) is sent
     * as data stream annotations (custom JSON messages) alongside the text stream.
     */
    @Post('stream')
    @Allow(Permission.Public)
    async stream(@Ctx() ctx: RequestContext, @Body() body: AiChatRequest, @Res() res: Response): Promise<void> {
        const { customerId, ownerKey, limitKey, ip } = await this.resolveCustomer(ctx);
        const { message: query, history, conversationId } = await this.resolveHistory(body, ownerKey);

        if (!query) {
            res.setHeader('Content-Type', 'application/json');
            res.status(200).json({
                message: 'Hi! I\'m your shopping assistant. How can I help you today?',
                products: [],
                collections: [],
            });
            return;
        }

        await this.chatLimits.checkBeforeChat('shop', limitKey, ip);

        // Stop generating (and spending tokens) if the shopper disconnects mid-answer.
        const abort = new AbortController();
        res.on('close', () => {
            if (!res.writableFinished) {
                abort.abort();
            }
        });
        const streamResult = this.aiChatService.streamChat(ctx, query, history, customerId, abort.signal);

        // Use the AI SDK's toUIMessageStreamResponse for useChat() compatibility
        const streamResponse = streamResult.toUIMessageStreamResponse();

        // Forward status and headers
        res.status(streamResponse.status ?? 200);
        streamResponse.headers.forEach((value: string, key: string) => {
            res.setHeader(key, value);
        });

        // Pipe the body stream to the express response
        if (streamResponse.body) {
            const reader = streamResponse.body.getReader();
            try {
                while (true) {
                    const { done, value } = await reader.read();
                    if (done) break;
                    res.write(value);
                }
            } catch (e) {
                this.logger.error(`Stream error: ${e}`);
            } finally {
                res.end();
            }
        } else {
            res.end();
        }

        try {
            await this.chatLimits.recordUsage('shop', limitKey, (await streamResult.totalUsage).totalTokens);
        } catch {
            // usage is unavailable if the stream was aborted
        }

        // Cache the new conversation turn after the stream completes.
        // We await the full text from the streamResult (which is already
        // consumed by the stream pipe above, so .text resolves immediately).
        if (conversationId) {
            try {
                const fullText = await streamResult.text;
                // Keep tool summaries (e.g. product variantIds) so follow-ups like
                // "add the second one to my cart" still have the context they need.
                const toolSummaries = (await streamResult.steps)
                    .flatMap(step => step.toolResults ?? [])
                    .map(r => (r as { output?: { summary?: unknown } }).output?.summary)
                    .filter((summary): summary is string => typeof summary === 'string')
                    .map(summary => `[Tool result: ${summary}]`);
                await this.conversationCacheService.appendMessages(
                    ownerKey,
                    conversationId,
                    query,
                    [fullText, ...toolSummaries].filter(Boolean).join('\n'),
                    customerId,
                    this.options.maxHistoryMessages ?? 20,
                );
            } catch (e) {
                this.logger.error(`Failed to cache conversation turn: ${e}`);
            }
        }
    }
}
